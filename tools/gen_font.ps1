# Renders ASCII 32..126 as an 8x16 1-bit font with Windows GDI+ and writes a C header.
# usage: powershell -File gen_font.ps1 [-Out ..\shim\font.h] [-Face Consolas] [-Preview "A@g"]
param([string]$Out = "$PSScriptRoot\..\shim\font.h", [string]$Face = "Consolas", [string]$Preview = "")
Add-Type -AssemblyName System.Drawing
$font = New-Object System.Drawing.Font($Face, 14, [System.Drawing.FontStyle]::Bold, [System.Drawing.GraphicsUnit]::Pixel)
$fmt = [System.Drawing.StringFormat]::GenericTypographic
$rows = New-Object System.Collections.Generic.List[string]
foreach ($c in 32..126) {
    $bmp = New-Object System.Drawing.Bitmap(8, 16)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::SingleBitPerPixelGridFit
    $g.Clear([System.Drawing.Color]::Black)
    $g.DrawString([string][char]$c, $font, [System.Drawing.Brushes]::White, 0, 0, $fmt)
    $bytes = foreach ($y in 0..15) {
        $b = 0
        foreach ($x in 0..7) { if ($bmp.GetPixel($x, $y).R -gt 127) { $b = $b -bor (0x80 -shr $x) } }
        $b
    }
    if ($Preview.Contains([string][char]$c)) {
        foreach ($b in $bytes) { [Convert]::ToString($b, 2).PadLeft(8, '0').Replace('0', '.').Replace('1', '#') }
    }
    $rows.Add("    {" + (($bytes | ForEach-Object { "0x{0:x2}" -f $_ }) -join ",") + "}, /* " + $(if ($c -eq 92) { "backslash" } else { [char]$c }) + " */")
    $g.Dispose(); $bmp.Dispose()
}
$text = "/* Generated by tools/gen_font.ps1 ($Face bold, 8x16, ASCII 32..126). Bit 7 is the left pixel. */`n" +
        "static const unsigned char font8x16[95][16] = {`n" + ($rows -join "`n") + "`n};`n"
[System.IO.File]::WriteAllText($Out, $text)
"wrote $Out"
